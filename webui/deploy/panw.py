def _paf_r_description(rule, ctx):
    ff = ctx["force_fallback"]
    desc = rule.get("description") or rule.get("rule_name") or ""
    if ff and desc:
        desc = f"{desc} [fallback]"
    elif ff:
        desc = "fallback"
    if not desc:
        return []
    if len(desc) > 1023 and not ff:
        ctx["dropped"].append(DroppedField(
            rule_id=ctx["rule_id"], field="description",
            reason=f"exceeds PAN-OS 1023-char limit ({len(desc)} chars)",
            fallback="truncated to 1023 chars"))
    return [_el("description", desc[:1023])]


