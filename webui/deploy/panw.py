    def list_security_profiles(self, *, device: dict,
                               scopes: list[str] | None = None) -> dict[str, list[dict]]:
        """Read PA's per-rule attachable profile catalog.

        Returns {category: [{"name": str, "predefined": bool}, ...]} for the
        categories under ``vsys/profiles`` plus ``profile-group``. Predefined
        entries (shipped by PAN-OS, not visible at vsys XPath) are merged in
        from a static list so the catalog mirrors the rule-attachment dropdown
        in the PA GUI. Read-only - Gateshift doesn't manage profiles.

        ``scopes``: for a PANORAMA target, the device-group inheritance chain
        (nearest-first) the rule resolves against - read those device-groups +
        ``shared`` instead of the (non-existent) firewall vsys. None/empty = a
        standalone firewall (vsys + shared, the default).
        """
        base_url = _api_url(device)
        api_key = device.get("api_key") or ""
        if not api_key:
            raise RuntimeError("No API key configured for target")

        # Profiles and profile-groups can live in the vsys OR in the shared
        # location (PA resolves a rule reference against both). Read each scope
        # and union the names, else shared groups/profiles are invisible to the
        # catalog and look "missing" even though the target has them.
        def _names_at(xpath: str, cat: str) -> list[str]:
            resp = requests.post(
                f"{base_url}/api/",
                data={"type": "config", "action": "get", "xpath": xpath},
                headers={"X-PAN-KEY": api_key},
                verify=False,
                timeout=(_CONNECT_TIMEOUT, 30),
            )
            resp.raise_for_status()
            root = ET.fromstring(resp.text)
            if root.attrib.get("status") == "success":
                return [e.attrib.get("name") for e in root.findall(".//entry")
                        if e.attrib.get("name")]
            # Missing element on the device is normal (e.g. dns-security absent
            # on older PAN-OS, or no shared profiles) - not an error.
            msg = (root.findtext("msg") or "").lower()
            if not ("no such node" in msg or "could not find" in msg):
                detail = root.findtext("msg") or root.findtext(".//line") or resp.text[:300]
                raise RuntimeError(f"PAN-OS {cat} lookup failed: {detail}")
            return []

        # Panorama: read the device-group chain + shared (a rule in a DG resolves
        # profiles up the DG parents to shared). Firewall: the vsys + shared.
        if scopes:
            scope_bases = [f"{_DEV}/device-group/entry[@name='{dg}']" for dg in scopes]
            scope_bases.append("/config/shared")
        else:
            scope_bases = [_VSYS, "/config/shared"]

        out: dict[str, list[dict]] = {}
        for cat in (*self._PROFILE_CATEGORIES, "profile-group"):
            rel = "profile-group" if cat == "profile-group" else f"profiles/{cat}"
            custom: list[str] = []
            seen: set[str] = set()
            for scope_base in scope_bases:
                for name in _names_at(f"{scope_base}/{rel}", cat):
                    if name not in seen:
                        seen.add(name)
                        custom.append(name)

            predefined = self._PREDEFINED_PROFILES.get(cat, ())
            custom_set = set(custom)
            items: list[dict] = []
            for name in predefined:
                # If a custom profile shadows the predefined name on the device,
                # PA uses the custom one - flag the entry as custom in that case.
                items.append({"name": name, "predefined": name not in custom_set})
            for name in custom:
                if name in predefined and name in custom_set:
                    # Already added (shadowed predefined slot); skip duplicate.
                    continue
                items.append({"name": name, "predefined": False})
            items.sort(key=lambda d: (not d["predefined"], d["name"].lower()))
            out[cat] = items
        return out

    def list_applications(self, *, device: dict) -> dict[str, list[dict]]:
        """Read PA's full application catalog.

        Returns four buckets (`application`, `application-group`,
        `application-filter`, `application-predefined`). For `application` and
        `application-predefined` each entry carries a ``default_ports`` list
        (e.g. ``["tcp/443", "udp/53,5353"]``) extracted from PA's
        ``<default><port>`` block. Empty list = signature-only app (no fixed
        port). Used for port→app candidate suggestion during rule enrichment.

        Predefined apps are included so downstream rule-enrichment can resolve
        any app-name the source rule references. The UI filters them out of
        the catalog view (huge + read-only) but keeps them in cache.
        """
        base_url = _api_url(device)
        api_key = device.get("api_key") or ""
        if not api_key:
            raise RuntimeError("No API key configured for target")

        def _post(data: dict[str, str], label: str) -> ET.Element:
            resp = requests.post(
                f"{base_url}/api/",
                data=data,
                headers={"X-PAN-KEY": api_key},
                verify=False,
                timeout=(_CONNECT_TIMEOUT, 120),  # predefined-app dump is ~13 MB
            )
            resp.raise_for_status()
            root = ET.fromstring(resp.text)
            if root.attrib.get("status") != "success":
                msg = (root.findtext("msg") or "").lower()
                if "no such node" in msg or "could not find" in msg:
                    return ET.Element("result")  # vsys empty for that category
                detail = root.findtext("msg") or root.findtext(".//line") or resp.text[:300]
                raise RuntimeError(f"PAN-OS {label} lookup failed: {detail}")
            return root

        def _default_ports(entry: ET.Element) -> list[str]:
            """PA <default><port><member> values verbatim - keep PA's syntax
            (``tcp/443``, ``tcp/389,3268``, ``tcp/100-200``) so the matcher
            stays driver-side and the cache stays vendor-shape-true."""
            ports: list[str] = []
            port_node = entry.find("./default/port")
            if port_node is not None:
                for m in port_node.findall("./member"):
                    if m.text:
                        ports.append(m.text.strip())
            return ports

        out: dict[str, list[dict]] = {}

        # Custom (vsys-scoped) apps + groups + filters via config-get.
        for cat in ("application", "application-group", "application-filter"):
            root = _post(
                {"type": "config", "action": "get", "xpath": f"{_VSYS}/{cat}"},
                label=cat,
            )
            items: list[dict] = []
            for e in root.findall(".//entry"):
                name = e.attrib.get("name")
                if not name:
                    continue
                item: dict = {"name": name, "predefined": False}
                if cat == "application":
                    item["default_ports"] = _default_ports(e)
                items.append(item)
            items.sort(key=lambda d: d["name"].lower())
            out[cat] = items

        # Predefined (content-DB) apps via op-command - bulk dump returns
        # full <entry> XML, so we get default-port info in the same call.
        root = _post(
            {"type": "op", "cmd": (
                "<show><predefined><xpath>/predefined/application</xpath></predefined></show>"
            )},
            label="predefined application",
        )
        predef: list[dict] = []
        for e in root.findall(".//entry"):
            name = e.attrib.get("name")
            if not name:
                continue
            predef.append({
                "name": name,
                "predefined": True,
                "default_ports": _default_ports(e),
            })
        predef.sort(key=lambda d: d["name"].lower())
        out["application-predefined"] = predef
        return out

