    def _resolve_active_node(self, device: dict) -> dict:
        """For an HA pair, return the device dict of the ACTIVE member.

        A pair-registered device carries its peer in ``config.pa.ha_peer``
        ({mgmt_ip, api_key}). We push to the ACTIVE member - PAN-OS config-sync
        replicates to the passive, and pushing to a passive would be overwritten
        by sync. Query this node's HA state: passive → switch to the peer; active
        (or HA disabled / no peer / can't tell) → use this node as-is (standalone
        behavior). Best-effort; never raises."""
        try:
            cfg = json.loads(device.get("config") or "{}")
        except Exception:
            cfg = {}
        peer = ((cfg.get("pa") or {}).get("ha_peer")) or {}
        if not (peer.get("mgmt_ip") and peer.get("api_key")):
            return device  # not registered as an HA pair
        try:
            st = self._api_op(
                device,
                "<show><high-availability><state></state></high-availability></show>")
            local = (st.findtext(".//group/local-info/state") or "").lower()
        except Exception:
            return device  # can't determine → use as-is
        if local == "passive":
            return {**device, "mgmt_ip": peer["mgmt_ip"], "api_key": peer["api_key"]}
        return device

    def _ha_reserved_interfaces(self, device: dict) -> set[str]:
        """Interface names reserved for HA (HA1/HA2/HA3 + backups), read from
        ``/deviceconfig/high-availability``. The network wipe must NOT delete
        these - clobbering an HA data-interface (ethernet-based HA) breaks the
        cluster on commit. Empty for a standalone device or management-based HA
        port → the wipe stays coarse. Best-effort."""
        try:
            ha = self._api_get(device, f"{_DEV}/deviceconfig/high-availability")
        except Exception:
            return set()
        return {p.text.strip() for p in ha.iter("port")
                if p is not None and p.text and p.text.strip()}

    @staticmethod
    def _iface_ips(entry: ET.Element) -> list[str]:
        """Collect <ip><entry name="X"/></ip> values from an interface entry."""
        ip_el = entry.find("ip")
        if ip_el is None:
            return []
        out: list[str] = []
        for e in ip_el.findall("entry"):
            name = e.attrib.get("name")
            if name:
                out.append(name)
        return out

    def list_target_interfaces(self, *, device: dict) -> list[dict]:
        """Read PA interface configuration via /network/interface."""
        result = self._api_get(device, f"{_NET}/interface")
        out: list[dict] = []

        def _has_dhcp(parent_el):
            """Return True if the layer3 block carries a <dhcp-client>
            with enable=yes (or no explicit <enable> at all - defaults to
            on in PAN-OS)."""
            if parent_el is None:
                return False
            d = parent_el.find("dhcp-client")
            if d is None:
                return False
            enable_el = d.find("enable")
            if enable_el is None:
                return True
            return (enable_el.text or "").strip().lower() in ("yes", "true", "1")

        # First pass over <ethernet> to build the aggregate-group membership
        # map - each physical iface that's a slave carries
        # <aggregate-group>aeN</aggregate-group> pointing at its bond.
        ae_members: dict[str, list[str]] = {}
        for eth_parent in (result.find("interface/ethernet") or result.find("ethernet") or ET.Element("_")).findall("entry"):
            pname = eth_parent.attrib.get("name") or ""
            ag = eth_parent.find("aggregate-group")
            if pname and ag is not None and (ag.text or "").strip():
                ae_members.setdefault(ag.text.strip(), []).append(pname)
        for ae in ae_members:
            ae_members[ae].sort()

        # Ethernet: parent + units (subinterfaces)
        for eth_parent in (result.find("interface/ethernet") or result.find("ethernet") or ET.Element("_")).findall("entry"):
            pname = eth_parent.attrib.get("name") or ""
            if not pname:
                continue
            l3 = eth_parent.find("layer3")
            parent_ips = self._iface_ips(l3) if l3 is not None else []
            comment = eth_parent.findtext("comment") or None
            # PA admin-state: `<link-state>` at the iface entry. Values are
            # `auto` (default - link follows physical), `up` (force up),
            # `down` (admin disable). Absent element = `auto` = enabled.
            link_state = (eth_parent.findtext("link-state") or "auto").strip().lower()
            enabled_p = link_state != "down"
            out.append({
                "name": pname,
                "type": "ethernet",
                "ip_addresses": parent_ips,
                "zone": None,
                "description": comment,
                "dhcp_enabled": _has_dhcp(l3),
                "enabled": enabled_p,
            })
            # Subinterfaces under <units>
            units = (l3.find("units") if l3 is not None else None)
            if units is not None:
                for sub in units.findall("entry"):
                    sname = sub.attrib.get("name") or ""
                    if not sname:
                        continue
                    out.append({
                        "name": sname,
                        "type": "ethernet",
                        "ip_addresses": self._iface_ips(sub),
                        "zone": None,
                        "description": sub.findtext("comment") or None,
                        "dhcp_enabled": _has_dhcp(sub),
                    })

        # Aggregate-ethernet: bond parents + their units (VLAN subs on bond).
        # member_iface_names comes from the ae_members map built above.
        for ae_parent in (result.find("interface/aggregate-ethernet") or result.find("aggregate-ethernet") or ET.Element("_")).findall("entry"):
            ae_name = ae_parent.attrib.get("name") or ""
            if not ae_name:
                continue
            l3 = ae_parent.find("layer3")
            ae_ips = self._iface_ips(l3) if l3 is not None else []
            link_state = (ae_parent.findtext("link-state") or "auto").strip().lower()
            out.append({
                "name": ae_name,
                "type": "bond",
                "ip_addresses": ae_ips,
                "zone": None,
                "description": ae_parent.findtext("comment") or None,
                "dhcp_enabled": _has_dhcp(l3),
                "enabled": link_state != "down",
                "members": ae_members.get(ae_name, []),
            })
            units = (l3.find("units") if l3 is not None else None)
            if units is not None:
                for sub in units.findall("entry"):
                    sname = sub.attrib.get("name") or ""
                    if not sname:
                        continue
                    out.append({
                        "name": sname,
                        "type": "ethernet",
                        "ip_addresses": self._iface_ips(sub),
                        "zone": None,
                        "description": sub.findtext("comment") or None,
                        "dhcp_enabled": _has_dhcp(sub),
                    })

        # Tunnel / loopback / vlan: under <units>
        for itype in ("tunnel", "loopback", "vlan"):
            container = result.find(f"interface/{itype}") or result.find(itype)
            if container is None:
                continue
            units = container.find("units")
            if units is None:
                continue
            for sub in units.findall("entry"):
                sname = sub.attrib.get("name") or ""
                if not sname:
                    continue
                out.append({
                    "name": sname,
                    "type": itype,
                    "ip_addresses": self._iface_ips(sub),
                    "zone": None,
                    "description": sub.findtext("comment") or None,
                    "dhcp_enabled": _has_dhcp(sub),
                })

        # Enrich with zone bindings from vsys/zone - one round-trip more,
        # cheap, and gives the user a meaningful "current zone at target" column.
        try:
            zones = self.list_target_zones(device=device)
            iface_to_zone: dict[str, str] = {}
            for z in zones:
                for iface in z.get("interfaces") or []:
                    iface_to_zone[iface] = z["name"]
            for entry in out:
                entry["zone"] = iface_to_zone.get(entry["name"])
        except Exception:
            # If zones can't be read, leave zone=None - interfaces still useful
            pass

        # Hardware ports: /network/interface only lists ports that have been
        # added to the layer3 config. The Interface-Mapping dropdown also
        # needs unconfigured-but-physically-present ports so the user can
        # target them in a push. ``show interface "hardware"`` enumerates
        # the chassis. Skip silently if op-cmd is unavailable (e.g. CN-series
        # VM that doesn't expose hardware) - the config-derived list still
        # works.
        try:
            hw_result = self._api_op(device, "<show><interface>hardware</interface></show>")
            seen = {e["name"] for e in out}
            hw_root = hw_result.find("hw") or hw_result
            for entry in hw_root.findall("entry"):
                hname = (entry.findtext("name") or "").strip()
                if not hname or hname in seen:
                    continue
                # Filter to ethernet*/aeN - skip management / dataplane-internal
                # interfaces that aren't user-assignable as layer3 targets.
                if not (hname.startswith("ethernet") or hname.startswith("ae")):
                    continue
                out.append({
                    "name": hname,
                    "type": "ethernet",
                    "ip_addresses": [],
                    "zone": None,
                    "description": None,
                })
                seen.add(hname)
        except Exception:
            pass

        return out

    def list_target_zones(self, *, device: dict) -> list[dict]:
        """Read PA zone configuration via /vsys/.../zone.

        Returns [{"name", "interfaces", "properties": {pa_*}}]. Properties
        carry the vendor-prefixed keys used elsewhere in the codebase
        (`fw_zones.properties`, _gen_zones renderer).
        """
        if self._zones_cache is not None:
            return self._zones_cache
        result = self._api_get(device, f"{_VSYS}/zone")
        out: list[dict] = []
        zone_root = result.find("zone") or result
        for entry in zone_root.findall("entry"):
            name = entry.attrib.get("name") or ""
            if not name:
                continue
            net = entry.find("network")
            zone_type = "layer3"
            members: list[str] = []
            zpp = None
            log_setting = None
            packet_buffer = False
            if net is not None:
                for child in net:
                    if child.tag in ("layer3", "layer2", "virtual-wire", "tap", "tunnel", "external"):
                        zone_type = child.tag
                        members = [m.text for m in child.findall("member") if m.text]
                        break
                zpp = (net.findtext("zone-protection-profile") or "").strip() or None
                log_setting = (net.findtext("log-setting") or "").strip() or None
                packet_buffer = (net.findtext("enable-packet-buffer-protection") or "").lower() == "yes"
            user_id = (entry.findtext("enable-user-identification") or "").lower() == "yes"
            device_id = (entry.findtext("enable-device-identification") or "").lower() == "yes"
            out.append({
                "name": name,
                "interfaces": members,
                "properties": {
                    "pa_zone_type":                       zone_type,
                    "pa_zone_protection_profile":         zpp,
                    "pa_log_setting":                     log_setting,
                    "pa_enable_user_id":                  user_id,
                    "pa_enable_device_id":                device_id,
                    "pa_enable_packet_buffer_protection": packet_buffer,
                },
            })
        self._zones_cache = out
        return out

    def list_target_routes(self, *, device: dict) -> list[dict]:
        """Read PA static routes - legacy /network/virtual-router AND the Advanced
        Routing Engine /network/logical-router (PAN-OS 10.2+). A box is EITHER
        legacy VR OR ARE LR, so reading both + merging is safe (the absent node
        returns empty). An LR entry name is the routing-instance identity
        (= vr_name); the vrf entry is always 'default' (platform-gated)."""
        result = self._api_get(device, f"{_NET}/virtual-router")
        out: list[dict] = []
        vr_root = result.find("virtual-router") or result
        for vr in vr_root.findall("entry"):
            vr_name = vr.attrib.get("name") or "default"
            static = vr.find("routing-table/ip/static-route")
            if static is None:
                continue
            for rt in static.findall("entry"):
                prefix = rt.findtext("destination") or ""
                if not prefix:
                    continue
                iface = rt.findtext("interface") or None
                next_hop = rt.findtext("nexthop/ip-address") or None
                out.append({
                    "prefix": prefix,
                    "interface_name": iface,
                    "next_hop": next_hop,
                    "vr_name": vr_name,
                    "is_connected": False,
                })
        # Advanced Routing Engine: the same static routes live one level deeper,
        # under logical-router/entry/vrf/entry/routing-table (empty on a legacy box).
        lr_root = self._api_get(device, f"{_NET}/logical-router")
        lr_root = lr_root.find("logical-router") or lr_root
        for lr in lr_root.findall("entry"):
            lr_name = lr.attrib.get("name") or "default"
            for static in lr.findall("vrf/entry/routing-table/ip/static-route"):
                for rt in static.findall("entry"):
                    prefix = rt.findtext("destination") or ""
                    if not prefix:
                        continue
                    out.append({
                        "prefix": prefix,
                        "interface_name": rt.findtext("interface") or None,
                        "next_hop": rt.findtext("nexthop/ip-address") or None,
                        "vr_name": lr_name,
                        "is_connected": False,
                    })
        return out

    def list_target_vrfs(self, *, device: dict) -> list[dict]:
        """Read PA routing instances as first-class VRFs - legacy virtual-routers
        AND ARE logical-routers (PAN-OS 10.2+; the other mode reads empty). Emits
        interface_members + minimal properties (legacy ecmp only - BGP/OSPF are
        deferred, enterprise-backlog). For ARE the logical-router entry name is the
        VRF identity and members live under vrf/entry/interface/member.
        """
        result = self._api_get(device, f"{_NET}/virtual-router")
        out: list[dict] = []
        vr_root = result.find("virtual-router") or result
        for vr in vr_root.findall("entry"):
            name = (vr.attrib.get("name") or "").strip()
            if not name:
                continue
            members = [
                (m.text or "").strip()
                for m in vr.findall("interface/member")
                if (m.text or "").strip()
            ]
            properties: dict = {}
            ecmp_el = vr.find("ecmp")
            if ecmp_el is not None:
                ecmp: dict = {}
                for child in ecmp_el:
                    if len(child) == 0:
                        val = (child.text or "").strip()
                        if val:
                            ecmp[child.tag] = val
                if ecmp:
                    properties["ecmp"] = ecmp
            out.append({
                "name": name,
                "interface_members": members,
                "properties": properties or None,
            })
        # Advanced Routing Engine: logical-router entries are the VRFs; interface
        # members live under vrf/entry/interface/member (empty on a legacy box).
        lr_root = self._api_get(device, f"{_NET}/logical-router")
        lr_root = lr_root.find("logical-router") or lr_root
        for lr in lr_root.findall("entry"):
            name = (lr.attrib.get("name") or "").strip()
            if not name:
                continue
            members = [
                (m.text or "").strip()
                for m in lr.findall("vrf/entry/interface/member")
                if (m.text or "").strip()
            ]
            out.append({
                "name": name,
                "interface_members": members,
                "properties": None,
            })
        return out

    def list_target_addresses(self, *, device: dict) -> list[dict]:
        """Read PA address-objects via vsys/address."""
        try:
            result = self._api_get(device, f"{_VSYS}/address")
        except Exception:
            return []
        out: list[dict] = []
        root = result.find("address") or result
        for entry in root.findall("entry"):
            name = entry.attrib.get("name") or ""
            if not name:
                continue
            atype: str | None = None
            value: str | None = None
            for kind in ("ip-netmask", "ip-range", "fqdn"):
                v = entry.findtext(kind)
                if v:
                    atype = kind
                    value = v.strip()
                    break
            out.append({"name": name, "type": atype, "value": value})
        return out

    def list_target_services(self, *, device: dict) -> list[dict]:
        """Read PA service-objects via vsys/service."""
        try:
            result = self._api_get(device, f"{_VSYS}/service")
        except Exception:
            return []
        out: list[dict] = []
        root = result.find("service") or result
        for entry in root.findall("entry"):
            name = entry.attrib.get("name") or ""
            if not name:
                continue
            proto_el = entry.find("protocol")
            proto: str | None = None
            port: str | None = None
            if proto_el is not None:
                for p in ("tcp", "udp", "sctp"):
                    p_el = proto_el.find(p)
                    if p_el is not None:
                        proto = p
                        port = (p_el.findtext("port") or "").strip() or None
                        break
            out.append({"name": name, "proto": proto, "port": port})
        return out

