# PA object names allow letters, digits, '.', '-', '_'. Anything else (notably
# '/' from auto-name fallbacks like 'udp/11335') is invalid and PA rejects
# it on commit. PA also requires the first char to be alphanumeric - ASA-side
# autogenerated names like '_inline_S_tcp_53' fail with "X is invalid" until
# we strip the leading underscore. _safe_pa_name normalizes any name to that
# subset.
_PA_NAME_SAFE_RE = _re.compile(r"[^A-Za-z0-9._\-]")
_PA_NAME_LEAD_RE = _re.compile(r"^[^A-Za-z0-9]+")
_PA_NAME_MAX_LEN = 63


def _safe_pa_name(name: str) -> str:
    s = _PA_NAME_SAFE_RE.sub("-", name or "")
    s = _PA_NAME_LEAD_RE.sub("", s)
    return s[:_PA_NAME_MAX_LEN] or "obj"


