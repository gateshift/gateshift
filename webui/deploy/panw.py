# ── Field-level patch (Optimization O-2) ─────────────────────────
# The same field-spec (builders above) that RENDERS a whole object also drives the
# in-place PATCH: build the DESIRED entry, diff its OWNED fields against the object's
# RAW baseline (fw_raw_objects), emit the minimal action=edit/delete ops. Owned tags
# = the child elements the spec can produce; everything else on the box (the uuid
# attribute, any unmodeled element) is never referenced → survives server-side. This
# is what makes same-vendor in-place optimization lossless.

_PA_OWNED_TAGS = {
    "address":       ("ip-netmask", "ip-range", "fqdn", "description"),
    "address-group": ("static", "dynamic", "description"),
    "service":       ("protocol", "description"),
    "service-group": ("members",),
    "rule":          ("from", "to", "source", "destination", "application",
                      "category", "service", "action", "log-start", "log-end",
                      "profile-setting", "log-setting", "tag", "group-tag",
                      "schedule", "source-user", "disabled", "negate-source",
                      "negate-destination", "description"),
}


def _pa_canon(el):
    """Whitespace-insensitive canonical form of an element for diffing (tag, sorted
    attrs, stripped text, canon children) - lets a raw node (pretty-printed by the
    API) compare equal to a freshly-built desired node."""
    return (el.tag,
            tuple(sorted(el.attrib.items())),
            (el.text or "").strip(),
            [_pa_canon(c) for c in el])


def _pa_build_entry(name, obj, ctx, builders):
    """Render ONE desired <entry name=..> from the field-spec builders (no root
    container, no _indent) - the desired side of the patch diff."""
    entry = _el("entry", None, name=name)
    for build in builders:
        for child in build(obj, ctx):
            entry.append(child)
    return entry


def _pa_field_patch_ops(raw_entry, desired_entry, owned_tags):
    """Minimal patch to converge raw_entry's OWNED fields to desired_entry's,
    touching nothing else. Returns [(action, tag, element|None)]: 'edit' replaces/
    creates a field node, 'delete' removes an owned field that's gone. Per-tag
    (order-independent). Unowned raw children + the entry attrs (uuid) are never
    referenced → preserved by the box."""
    ops = []
    for tag in owned_tags:
        d = desired_entry.findall(tag)
        r = raw_entry.findall(tag)
        if [_pa_canon(e) for e in d] == [_pa_canon(e) for e in r]:
            continue
        if d:
            for el in d:
                ops.append(("edit", tag, el))
        else:
            ops.append(("delete", tag, None))
    return ops


def _pa_apply_field_patch(device, entry_xpath, ops):
    """Apply field-patch ops to the object at entry_xpath: action=edit (replace an
    owned field node) / delete (remove one). Writes to the CANDIDATE (operator
    reviews + commits/reverts). Touches ONLY owned fields → the box keeps the uuid +
    any unmodeled element. Returns the applied [(action, tag)]."""
    base_url = _api_url(device)
    api_key = device.get("api_key") or ""
    applied = []
    for action, tag, el in ops:
        xp = f"{entry_xpath}/{tag}"
        if action == "edit":
            _api_edit(base_url, api_key, xp, _to_xml_str(el))
        elif action == "delete":
            _api_delete(base_url, api_key, xp)
        applied.append((action, tag))
    return applied


