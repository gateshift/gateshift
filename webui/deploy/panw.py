    # ── Security Rules XML ───────────────────────────────────────

    def _gen_rules(self, rules: list[dict], settings: dict[str, str],
                   dropped: list[DroppedField],
                   addr_lookup: dict[str, str],
                   svc_lookup: dict[tuple[str, str], str],
                   dropped_l3_svcs: set[str],
                   pushable_addrs: set[str] | None = None) -> str:
        prefix = settings.get("rule_prefix", "Gateshift-")
        legacy_profile_group = settings.get("security_profile_group", "").strip()
        log_fwd = settings.get("log_forwarding", "").strip()
        tag = settings.get("tag", "").strip()
        default_app = settings.get("default_app", "any").strip() or "any"
        # Fallback ruleset: clone every rule below the main set with zones AND
        # application forced to 'any'. The concrete service (port) stays - port
        # boundary preserved, zone + App-ID restrictions fall away. Lets rules
        # match even when the target's zone topology or App-ID detection differs
        # from the source's. Clones carry a '-fb' name suffix.
        append_fallback = _truthy(settings.get("append_fallback_ruleset", "false"))

        root = _el("rules")
        seen_names: dict[str, int] = {}

        def emit_rule(i: int, rule: dict, force_fallback: bool, name_suffix: str = "") -> None:
            rule_id = str(rule.get("rule_name") or rule.get("id") or f"#{i+1}")
            if not force_fallback:
                # Only flag dropped fields once (on the original pass).
                for fld in _UNSUPPORTED_RULE_FIELDS:
                    val = rule.get(fld)
                    if val:
                        dropped.append(DroppedField(
                            rule_id=rule_id, field=fld,
                            reason="not yet rendered by panw driver",
                        ))
            rule_name = _safe_pa_name(rule.get("rule_name") or f"{prefix}{i+1:03d}")
            if name_suffix:
                rule_name = _safe_pa_name(f"{rule_name}{name_suffix}")
            base = rule_name
            if base in seen_names:
                seen_names[base] += 1
                rule_name = _safe_pa_name(f"{base}-{seen_names[base]}")
            else:
                seen_names[base] = 0
            if rule_name not in seen_names:
                seen_names[rule_name] = 0
            entry = ET.SubElement(root, "entry", name=rule_name)
            ctx = {
                "force_fallback": force_fallback, "rule_id": rule_id,
                "default_app": default_app, "tag": tag, "log_fwd": log_fwd,
                "legacy_profile_group": legacy_profile_group,
                "addr_lookup": addr_lookup, "svc_lookup": svc_lookup,
                "dropped_l3_svcs": dropped_l3_svcs, "dropped": dropped,
                "pushable_addrs": pushable_addrs,
            }
            _prepare_rule_render(rule, ctx)
            for _build in _PA_RULE_FIELDS:
                for _child in _build(rule, ctx):
                    entry.append(_child)

        for i, rule in enumerate(rules):
            emit_rule(i, rule, force_fallback=False)

        if append_fallback:
            for i, rule in enumerate(rules):
                emit_rule(i, rule, force_fallback=True, name_suffix="-fb")

        _indent(root)
        return _to_xml_str(root)

    # ── NAT Rules XML ────────────────────────────────────────────

    def _gen_nat_rules(self, nat_rules: list[dict], dropped: list[DroppedField],
                       external_zone: str | None = None,
                       addr_lookup: dict[str, str] | None = None,
                       svc_lookup: dict[tuple[str, str], str] | None = None) -> str:
        """Generate PAN-OS <rulebase><nat><rules> XML.

        Renders the agnostic fw_nat_rules schema into PAN-OS NAT entries.
        Both source-translation (snat) and destination-translation (dnat) are
        supported; rules of nat_type='static' fall through to source-translation
        with type 'static-ip' if a translated source is present.

        addr_lookup/svc_lookup let raw IPs/services be rewritten to object
        names - same mechanism used by the security-rule renderer, so NAT
        rules and regular rules share the same object pool at the target.
        """
        addr_lookup = addr_lookup or {}
        svc_lookup = svc_lookup or {}

        def _rewrite_addrs(items: list[str]) -> list[str]:
            return [addr_lookup.get(x, x) for x in items]

        def _rewrite_svc(svc: str) -> str:
            # orig_service is "proto/port" - match it to a service object if known
            if not svc or svc == "any" or "/" not in svc:
                return svc or "any"
            proto, port_str = svc.split("/", 1)
            return svc_lookup.get((proto.lower(), port_str), svc)

        root = _el("rules")
        seen_nat_names: dict[str, int] = {}

        def _emit(base_name: str, svc_text: str, n: dict, rid: str) -> None:
            name = base_name
            if name in seen_nat_names:
                seen_nat_names[name] += 1
                name = _safe_pa_name(f"{base_name}-{seen_nat_names[base_name]}")
            else:
                seen_nat_names[name] = 0
            # nat_schemas pa_* slots - decoded once per rule so the
            # downstream blocks (static-ip xlate, group-tag) can read
            # without re-parsing.
            props = n.get("properties") or {}
            if isinstance(props, str):
                try:
                    import json as _json
                    props = _json.loads(props) or {}
                except Exception:
                    props = {}
            entry = ET.SubElement(root, "entry", name=name)

            from_el = ET.SubElement(entry, "from")
            _member_list(from_el, n.get("src_zones") or ["any"])

            # PAN-OS NAT <to> takes a REAL zone - unlike a security rule it
            # rejects 'any'. Sources without a NAT destination zone (CheckPoint
            # models NAT zone-free) fall back to the zone flagged external,
            # which is the egress a SNAT/DNAT actually targets (QA finding).
            _dz = [z for z in (n.get("dst_zones") or []) if z and z != "any"]
            if not _dz:
                if external_zone:
                    _dz = [external_zone]
                    dropped.append(DroppedField(
                        rule_id=name, field="dst_zones",
                        reason="source NAT rule carries no destination zone and "
                               "PAN-OS NAT rejects 'any'",
                        fallback=f"using the external zone {external_zone!r}"))
                else:
                    dropped.append(DroppedField(
                        rule_id=name, field="nat_rule",
                        reason="no destination zone and no zone flagged external "
                               "on the source - PAN-OS NAT needs a concrete zone",
                        fallback="rule dropped; set the zone in Enrichment"))
                    root.remove(entry)
                    return
            to_el = ET.SubElement(entry, "to")
            _member_list(to_el, _dz)

            src_el = ET.SubElement(entry, "source")
            _member_list(src_el, _rewrite_addrs(n.get("orig_src") or ["any"]))

            dst_el = ET.SubElement(entry, "destination")
            _member_list(dst_el, _rewrite_addrs(n.get("orig_dst") or ["any"]))

            ET.SubElement(entry, "service").text = svc_text

            if n.get("interface_name"):
                ET.SubElement(entry, "to-interface").text = self._pa_iface_name(n["interface_name"])

            nat_type = (n.get("nat_type") or "snat").lower()
            trans_src = n.get("trans_src")
            trans_src_type = (n.get("trans_src_type") or "none").lower()
            # pa_src_translation_type (enrichment property) overrides the
            # imported trans_src_type column when set. This lets the user
            # promote `none` → `dynamic-ip-and-port` etc. without editing
            # the hash-input identity columns.
            _pa_st = (props.get("pa_src_translation_type") or "").strip().lower()
            if _pa_st and _pa_st != "none":
                trans_src_type = _pa_st
            # Phase-F cross-vendor mapping: pa_trans_src_ref / pa_trans_dst_ref
            # override the source-derived translation targets so a source rule
            # can be re-bound to a PA-target address-object. An override
            # implies static-ip translation (named object → static-ip xlate),
            # so we flip trans_src_type accordingly. Source-rules originally
            # using interface-address keep their semantics if no override is
            # set.
            _ts_ref = (props.get("pa_trans_src_ref") or "").strip()
            if _ts_ref:
                trans_src = _ts_ref
                trans_src_type = "static-ip"

            # Source translation (snat / static)
            if nat_type in ("snat", "static") and trans_src:
                src_xlate = ET.SubElement(entry, "source-translation")
                if trans_src_type == "interface-address":
                    ia = ET.SubElement(src_xlate, "dynamic-ip-and-port")
                    ia_el = ET.SubElement(ia, "interface-address")
                    # Use only <interface>; PAN-OS picks the interface's primary IP
                    # automatically.  Specifying an explicit <ip> requires an exact
                    # match against an IP entry on the interface (CIDR-named) and
                    # is rejected as "not a valid reference" otherwise - primary
                    # IP is the safe default for single-IP WAN interfaces.
                    iface = trans_src.split("|", 1)[0] if "|" in trans_src else trans_src
                    ET.SubElement(ia_el, "interface").text = iface
                else:
                    kind = trans_src_type if trans_src_type in (
                        "static-ip", "dynamic-ip", "dynamic-ip-and-port"
                    ) else "dynamic-ip-and-port"
                    k_el = ET.SubElement(src_xlate, kind)
                    if kind == "static-ip":
                        ET.SubElement(k_el, "translated-address").text = addr_lookup.get(trans_src, trans_src)
                        # pa_bi_directional only meaningful with static-ip src-xlate.
                        # Other modes (dynamic-ip / interface-address) silently
                        # ignore it; if set there, PA would reject the push.
                        if props.get("pa_bi_directional"):
                            ET.SubElement(k_el, "bi-directional").text = "yes"
                    else:
                        ta_el = ET.SubElement(k_el, "translated-address")
                        for v in (s.strip() for s in trans_src.split(",") if s.strip()):
                            ET.SubElement(ta_el, "member").text = addr_lookup.get(v, v)

            # Destination translation (dnat) - pa_trans_dst_ref overrides
            # the rendered translated-address when set. pa_dst_translation_type
            # chooses between static-ip (<destination-translation>) and
            # dynamic-ip (<dynamic-destination-translation>); static-ip
            # additionally accepts <dns-rewrite>, dynamic-ip a
            # <distribution> method.
            _td = n.get("trans_dst")
            _td_ref = (props.get("pa_trans_dst_ref") or "").strip()
            if _td_ref:
                _td = _td_ref
            _pa_dt = (props.get("pa_dst_translation_type") or "").strip().lower()
            if nat_type == "dnat" and (_td or n.get("trans_dst_port")):
                if _pa_dt == "dynamic-ip":
                    dst_xlate = ET.SubElement(entry, "dynamic-destination-translation")
                    if _td:
                        ET.SubElement(dst_xlate, "translated-address").text = addr_lookup.get(_td, _td)
                    _tp = _pa_xlate_port(n.get("trans_dst_port"), n, dropped)
                    if _tp:
                        ET.SubElement(dst_xlate, "translated-port").text = _tp
                    _sdm = (props.get("pa_session_distribution_method") or "").strip().lower()
                    if _sdm in ("round-robin", "source-ip-hash", "ip-modulo", "ip-hash", "least-sessions"):
                        ET.SubElement(dst_xlate, "distribution").text = _sdm
                else:
                    dst_xlate = ET.SubElement(entry, "destination-translation")
                    if _td:
                        ET.SubElement(dst_xlate, "translated-address").text = addr_lookup.get(_td, _td)
                    _tp = _pa_xlate_port(n.get("trans_dst_port"), n, dropped)
                    if _tp:
                        ET.SubElement(dst_xlate, "translated-port").text = _tp
                    if props.get("pa_dns_rewrite"):
                        dns = ET.SubElement(dst_xlate, "dns-rewrite")
                        _dir = (props.get("pa_dns_direction") or "reverse").strip().lower()
                        if _dir in ("reverse", "forward"):
                            ET.SubElement(dns, "direction").text = _dir

            if n.get("disabled"):
                ET.SubElement(entry, "disabled").text = "yes"

            # PA NAT rejects ALL three negate elements ("unexpected here")
            # - Live-API probe 2026-06-03 corrected the V0 assumption.
            # Warn for each flag the user (or source-import) had set; emit
            # nothing on the wire.
            for aspect in ("negate_source", "negate_destination", "negate_service"):
                if n.get(aspect):
                    dropped.append(DroppedField(
                        rule_id=rid, field=aspect,
                        reason="PAN-OS NAT rules do not support negation",
                        fallback="ignored",
                    ))

            # PA group-tag - entry-level, optional. Trimmed to 127 chars
            # (PA tag-name limit).
            gt = (props.get("pa_group_tag") or "").strip()
            if gt:
                ET.SubElement(entry, "group-tag").text = gt[:127]
            desc = n.get("description") or ""
            if desc:
                if len(desc) > 1023:
                    dropped.append(DroppedField(
                        rule_id=rid, field="description",
                        reason=f"exceeds PAN-OS 1023-char limit ({len(desc)} chars)",
                        fallback="truncated to 1023 chars",
                    ))
                ET.SubElement(entry, "description").text = desc[:1023]

        # PA NAT carries one service per entry. When the source rule has multiple
        # services we split into one PA entry per service so traffic across the
        # whole port set still matches - losing services here would silently
        # drop traffic on push.
        for i, n in enumerate(nat_rules):
            base_name = _safe_pa_name(n.get("name") or f"nat-{i+1:03d}")
            rid = base_name
            services = n.get("orig_service") or []
            if not services:
                _emit(base_name, "any", n, rid)
                continue
            for j, svc in enumerate(services):
                svc_text = _rewrite_svc(svc)
                if len(services) == 1:
                    entry_name = base_name
                else:
                    # Suffix splits with -s1/-s2/… so the original NAT name
                    # remains identifiable. _safe_pa_name re-applies length
                    # truncation in case the suffix pushed past 63 chars.
                    entry_name = _safe_pa_name(f"{base_name}-s{j+1}")
                _emit(entry_name, svc_text, n, rid)

        _indent(root)
        return _to_xml_str(root)

    def _gen_pbf(self, pbf_rules: list[dict],
                 dropped: list[DroppedField],
                 svc_lookup: dict | None = None,
                 svc_sink: list[dict] | None = None) -> str:
        """Generate PAN-OS PBF rulebase XML (`<pbf><rules>`) from agnostic
        policy-routes (Phase 3). ingress {name,type} drives <from><zone> vs
        <from><interface>; action(forward|discard|no-pbf). Vendor specials
        (PA source-user, symmetric-return) come from raw_extras (Routing-
        Enrichment overlay already merged in by _load_pbf_rules)."""
        root = _el("rules")
        for i, p in enumerate(pbf_rules):
            name = _safe_pa_name(p.get("name") or f"pbf-{i+1:03d}")
            entry = ET.SubElement(root, "entry", name=name)
            # ── Ingress: <from><zone> / <from><interface> (fund A) ──
            zones = [ing["name"] for ing in (p.get("ingress") or [])
                     if ing.get("type") == "zone" and ing.get("name")]
            ifaces = [ing["name"] for ing in (p.get("ingress") or [])
                      if ing.get("type") == "interface" and ing.get("name")]
            from_el = ET.SubElement(entry, "from")
            if zones:
                _member_list(ET.SubElement(from_el, "zone"), zones)
            if ifaces:
                _member_list(ET.SubElement(from_el, "interface"), ifaces)
            if not zones and not ifaces:
                # PAN-OS PBF has no 'any' ingress - <from><zone>any</zone>
                # is rejected as an invalid reference. A source rule without
                # an ingress binding (FortiOS allows it) therefore cannot be
                # represented; drop it rather than emit a rule that fails the
                # whole section (QA finding, Forti→PA).
                dropped.append(DroppedField(
                    rule_id=name, field="pbf_ingress",
                    reason="policy-route has no ingress zone/interface; PAN-OS "
                           "PBF requires one (no 'any' ingress) - rule dropped",
                    fallback="re-create it manually with the intended ingress"))
                root.remove(entry)
                continue
            _member_list(ET.SubElement(entry, "source"),
                         p.get("sources") or ["any"])
            _member_list(ET.SubElement(entry, "destination"),
                         p.get("destinations") or ["any"])
            # PA references SERVICE OBJECTS here - a cross-vendor
            # 'proto/port' literal (FortiOS policy-route protocol+ports) is
            # rejected as "not an allowed keyword". Resolve it against the
            # pushed services, else materialize one (QA finding, Forti→PA).
            _svcs = []
            for _sv in (p.get("services") or ["any"]):
                _txt = str(_sv or "").strip()
                if not _txt or _txt.lower() == "any":
                    _svcs.append("any")
                    continue
                if "/" in _txt:
                    _pr, _, _po = _txt.partition("/")
                    _pr, _po = _pr.lower(), _po.strip()
                    _hit = (svc_lookup or {}).get((_pr, _po))
                    if not _hit and svc_sink is not None and _pr in ("tcp", "udp") and _po:
                        _hit = _safe_pa_name(f"svc-{_pr}-{_po}")
                        if not any(o.get("name") == _hit for o in svc_sink):
                            svc_sink.append({
                                "name": _hit,
                                "value": {"protocol": _pr, "port": _po,
                                          "description": "materialized for a "
                                                         "policy-based-forwarding rule"},
                            })
                    if _hit:
                        _svcs.append(_hit)
                        continue
                    dropped.append(DroppedField(
                        rule_id=name, field="pbf_service",
                        reason=f"service {_txt!r} has no PA service object and "
                               "can't be materialized",
                        fallback="service narrowed to any"))
                    _svcs.append("any")
                    continue
                _svcs.append(_txt)
            _member_list(ET.SubElement(entry, "service"), _svcs or ["any"])

            raw = p.get("raw_extras") or {}
            # ── Vendor L7-match from raw_extras ──
            su = raw.get("pa_source_user")
            if su:
                _member_list(ET.SubElement(entry, "source-user"), su)
            apps = raw.get("pa_application")
            if apps:
                _member_list(ET.SubElement(entry, "application"), apps)

            # ── Action ──
            act_el = ET.SubElement(entry, "action")
            action = (p.get("action") or "forward").lower()
            if action == "discard":
                ET.SubElement(act_el, "discard")
            elif action == "no-pbf":
                ET.SubElement(act_el, "no-pbf")
            else:
                fwd = ET.SubElement(act_el, "forward")
                egress = (p.get("egress_interface") or "").strip()
                if egress:
                    ET.SubElement(fwd, "egress-interface").text = egress
                nh = (p.get("next_hop") or "").strip()
                if nh:
                    nh_el = ET.SubElement(fwd, "nexthop")
                    ET.SubElement(nh_el, "ip-address").text = nh

            # ── Specials from raw_extras ──
            if raw.get("pa_symmetric_return"):
                sym = ET.SubElement(entry, "enforce-symmetric-return")
                ET.SubElement(sym, "enabled").text = "yes"
            if raw.get("pa_negate_source"):
                ET.SubElement(entry, "negate-source").text = "yes"
            if raw.get("pa_negate_destination"):
                ET.SubElement(entry, "negate-destination").text = "yes"
            if p.get("disabled"):
                ET.SubElement(entry, "disabled").text = "yes"
        _indent(root)
        return _to_xml_str(root)

    def _gen_decryption(self, ssl_rules: list[dict],
                         dropped: list[DroppedField]) -> str:
        """Generate PAN-OS decryption rulebase XML (`<decryption><rules>`) from
        agnostic SSL-decryption rules (Phase 5). from/to→zones, source/dest,
        source-user, category(URL), service, action decrypt|no-decrypt, type
        ssl-forward-proxy, profile ref (raw_extras.pa_decryption_profile). V1 =
        HTTPS forward-proxy only; inbound/ssh collected-but-flagged rules are
        dropped+warned. The forward-trust CA is a firewall-global cert (the
        operator provisions it - ref-only), not a per-rule field."""
        root = _el("rules")
        for i, s in enumerate(ssl_rules):
            if s.get("deleted"):
                continue
            ssl_type = (s.get("ssl_type") or "forward-proxy")
            if ssl_type != "forward-proxy":
                dropped.append(DroppedField(
                    rule_id=s.get("name") or f"#{i+1}", field="decryption_type",
                    reason=f"'{ssl_type}' out of V1 scope (HTTPS forward-proxy "
                           "only) - collected, not pushed"))
                continue
            name = _safe_pa_name(s.get("name") or f"decrypt-{i+1:03d}")
            entry = ET.SubElement(root, "entry", name=name)
            _member_list(ET.SubElement(entry, "from"),
                         s.get("src_zones") or ["any"])
            _member_list(ET.SubElement(entry, "to"),
                         s.get("dst_zones") or ["any"])
            _member_list(ET.SubElement(entry, "source"),
                         _pa_addr_members(s.get("sources"), dropped, name, "ssl_source") or ["any"])
            _member_list(ET.SubElement(entry, "destination"),
                         _pa_addr_members(s.get("destinations"), dropped, name, "ssl_destination") or ["any"])
            su = [idn.get("name") for idn in (s.get("source_identities") or [])
                  if idn.get("name")]
            _member_list(ET.SubElement(entry, "source-user"), su or ["any"])
            _member_list(ET.SubElement(entry, "category"),
                         s.get("url_categories") or ["any"])
            _member_list(ET.SubElement(entry, "service"),
                         _pa_specials_to_any(s.get("services"), dropped, name, "ssl_service",
                                             _CP_SPECIAL_ANY_SVC, "predefined service") or ["any"])
            ET.SubElement(entry, "action").text = (
                s.get("action") or "decrypt")
            type_el = ET.SubElement(entry, "type")
            ET.SubElement(type_el, "ssl-forward-proxy")
            prof = (s.get("raw_extras") or {}).get("pa_decryption_profile")
            if prof:
                ET.SubElement(entry, "profile").text = prof
            if s.get("disabled"):
                ET.SubElement(entry, "disabled").text = "yes"
        _indent(root)
        return _to_xml_str(root)

    # ── IPSec VPN (CE plan P3a) ──────────────────────────────────
    # Render crypto profiles + IKE gateways + IPSec tunnels from the agnostic
    # model. Route-based S2S. The PSK is pushed as a PLACEHOLDER (operator sets
    # the real secret); cert-auth gateways are deferred (PA cert-auth structure
    # unverified on the lab). Builtin crypto profiles are skipped (they ship with
    # every PA). Canonical tokens are PA-native, so they render directly.
    _VPN_PSK_PLACEHOLDER = "GATESHIFT-PLACEHOLDER-PSK-CHANGE-ME"

    # PAN-OS caps each lifetime unit: seconds 180-65535, minutes 3-65535,
    # hours 1-65535, days 1-365. A source carrying e.g. FortiOS' keylife
    # 86400 SECONDS (= 1 day, a perfectly normal value) is rejected outright,
    # so promote the value to the largest unit it divides into cleanly before
    # emitting (QA finding, Forti→PA).
    _LIFETIME_MAX = {"seconds": 65535, "minutes": 65535, "hours": 65535, "days": 365}
    _LIFETIME_UP = {"seconds": ("minutes", 60), "minutes": ("hours", 60),
                    "hours": ("days", 24)}

    @classmethod
    def _gen_crypto_lifetime(cls, parent: "ET.Element", lifetime: dict | None,
                             default_hours: int | None = None) -> None:
        unit = (lifetime or {}).get("unit")
        val = (lifetime or {}).get("value")
        if unit not in cls._LIFETIME_MAX or not val:
            # A crypto profile WITHOUT <lifetime> is INVALID on PAN-OS (not
            # merely incomplete): the candidate fails validation and keeps
            # failing for every later push until fixed by hand (QA finding,
            # CP→PA - CP sources carry no lifetime). Emit the PAN-OS default.
            if default_hours:
                lt = ET.SubElement(parent, "lifetime")
                ET.SubElement(lt, "hours").text = str(default_hours)
            return
        try:
            val = int(val)
        except (TypeError, ValueError):
            return
        while val > cls._LIFETIME_MAX[unit] and unit in cls._LIFETIME_UP:
            nxt, factor = cls._LIFETIME_UP[unit]
            if val % factor:
                break          # can't promote without losing precision
            unit, val = nxt, val // factor
        if val > cls._LIFETIME_MAX[unit]:
            val = cls._LIFETIME_MAX[unit]
        lt = ET.SubElement(parent, "lifetime")
        ET.SubElement(lt, unit).text = str(val)

    def _gen_ike_crypto(self, profiles: list[dict],
                        dropped: list[DroppedField]) -> str:
        """Agnostic ike_crypto_profile objects → PAN-OS ike-crypto-profiles XML.
        Builtins skip (already on the target). Merge-push (no container wipe)."""
        root = _el("ike-crypto-profiles")
        for p in profiles:
            val = p.get("value") or {}
            if val.get("is_builtin"):
                continue
            name = _safe_pa_name(p.get("name") or "")
            if not name:
                continue
            entry = ET.SubElement(root, "entry", name=name)
            _member_list(ET.SubElement(entry, "encryption"), val.get("encryption") or [])
            _member_list(ET.SubElement(entry, "hash"), val.get("hash") or [])
            _member_list(ET.SubElement(entry, "dh-group"), val.get("dh_group") or [])
            self._gen_crypto_lifetime(entry, val.get("lifetime"), default_hours=8)
        _indent(root)
        return _to_xml_str(root)

    def _gen_ipsec_crypto(self, profiles: list[dict],
                          dropped: list[DroppedField]) -> str:
        """Agnostic ipsec_crypto_profile objects → PAN-OS ipsec-crypto-profiles
        XML. ESP/AH; pfs_group[0] → scalar <dh-group>. Builtins skip."""
        root = _el("ipsec-crypto-profiles")
        for p in profiles:
            val = p.get("value") or {}
            if val.get("is_builtin"):
                continue
            name = _safe_pa_name(p.get("name") or "")
            if not name:
                continue
            entry = ET.SubElement(root, "entry", name=name)
            proto = (val.get("protocol") or "esp").lower()
            pel = ET.SubElement(entry, "ah" if proto == "ah" else "esp")
            if proto != "ah":
                _member_list(ET.SubElement(pel, "encryption"), val.get("encryption") or [])
            _member_list(ET.SubElement(pel, "authentication"), val.get("auth") or [])
            pfs = val.get("pfs_group") or []
            ET.SubElement(entry, "dh-group").text = pfs[0] if pfs else "no-pfs"
            self._gen_crypto_lifetime(entry, val.get("lifetime"), default_hours=1)
        _indent(root)
        return _to_xml_str(root)

    def _gen_ike_gateways(self, vpn_tunnels: list[dict],
                          dropped: list[DroppedField]) -> str:
        """Agnostic vpn tunnels → PAN-OS ike-gateway XML. PSK → placeholder key
        (operator sets the real secret); cert auth deferred (DroppedField)."""
        root = _el("gateway")
        for v in vpn_tunnels:
            if v.get("deleted"):
                continue
            gw_name = _safe_pa_name(v.get("gateway_name") or v.get("name") or "")
            if not gw_name:
                continue
            auth_type = (v.get("auth_type") or "psk")
            cert_name = v.get("cert_name")
            # cert-auth needs an uploaded identity cert (CR-2). Without one the
            # gateway can't be rendered (a missing local-cert ref aborts the push
            # at set-time) → skip + tell the operator to upload it.
            if auth_type == "cert" and not cert_name:
                dropped.append(DroppedField(
                    rule_id=gw_name, field="ike_gateway",
                    reason="cert-auth: upload the local identity cert (PEM + key) "
                           "in the VPN tab to migrate this gateway"))
                continue
            entry = ET.SubElement(root, "entry", name=gw_name)
            auth = ET.SubElement(entry, "authentication")
            if auth_type == "cert":
                # Reference the uploaded identity cert by name; it is imported
                # server-side in the push's cert step before this gateway lands.
                cel = ET.SubElement(auth, "certificate")
                lc = ET.SubElement(cel, "local-certificate")
                ET.SubElement(lc, "name").text = cert_name
            else:
                psk = ET.SubElement(auth, "pre-shared-key")
                # Emit a per-tunnel token (carries vpn_hash, no secret). If the
                # operator stored a PSK in Gateshift it is injected server-side at
                # push; otherwise the token resolves to the placeholder. (Token
                # is safe in preview/audit - it round-trips through the browser.)
                vh = v.get("vpn_hash")
                ET.SubElement(psk, "key").text = (
                    f"__GATESHIFT_PSK_{vh}__" if vh else self._VPN_PSK_PLACEHOLDER)
                dropped.append(DroppedField(
                    rule_id=gw_name, field="pre_shared_key",
                    reason="PSK: a placeholder is pushed unless one is set in Gateshift "
                           "(then injected, encrypted, at push-time) - source secrets "
                           "are never migrated"))
            proto = ET.SubElement(entry, "protocol")
            ikev = v.get("ike_version") or "ikev2"
            ET.SubElement(proto, "version").text = ikev
            vtag = "ikev1" if ikev == "ikev1" else "ikev2"
            vel = ET.SubElement(proto, vtag)
            if v.get("ike_crypto_profile"):
                ET.SubElement(vel, "ike-crypto-profile").text = v["ike_crypto_profile"]
            la = ET.SubElement(entry, "local-address")
            if v.get("local_interface"):
                ET.SubElement(la, "interface").text = v["local_interface"]
            if v.get("local_address"):
                ET.SubElement(la, "ip").text = v["local_address"]
            ptype = v.get("peer_type") or "ip"
            peer = (v.get("peer_address") or "").strip()
            pa = ET.SubElement(entry, "peer-address")
            if ptype == "fqdn" and peer:
                ET.SubElement(pa, "fqdn").text = peer
            elif ptype == "dynamic" or not peer:
                ET.SubElement(pa, "dynamic")
            else:
                ET.SubElement(pa, "ip").text = peer
            if v.get("local_id"):
                ET.SubElement(entry, "local-id").text = v["local_id"]
            if v.get("peer_id"):
                ET.SubElement(entry, "peer-id").text = v["peer_id"]
        _indent(root)
        return _to_xml_str(root)

    def _gen_ipsec_tunnels(self, vpn_tunnels: list[dict],
                           dropped: list[DroppedField],
                           tunnel_iface_map: dict[str, str] | None = None) -> str:
        """Agnostic vpn tunnels → PAN-OS ipsec-tunnel XML (auto-key: ike-gateway +
        ipsec-crypto-profile + bound tunnel-interface). Policy-based peers emit a
        proxy-id per traffic-selector; route-based tunnels stay proxy-id-free.
        A cert-auth tunnel renders only when its identity cert is uploaded
        (else its gateway is skipped, so skip the tunnel too)."""
        root = _el("ipsec")
        for v in vpn_tunnels:
            if v.get("deleted"):
                continue
            if (v.get("auth_type") or "psk") == "cert" and not v.get("cert_name"):
                continue  # no identity cert uploaded → gateway skipped → skip tunnel
            name = _safe_pa_name(v.get("name") or "")
            if not name:
                continue
            entry = ET.SubElement(root, "entry", name=name)
            ak = ET.SubElement(entry, "auto-key")
            gw = ET.SubElement(ak, "ike-gateway")
            ET.SubElement(gw, "entry",
                          name=_safe_pa_name(v.get("gateway_name") or name))
            if v.get("ipsec_crypto_profile"):
                ET.SubElement(ak, "ipsec-crypto-profile").text = v["ipsec_crypto_profile"]
            # Policy-based peer: one proxy-id per traffic-selector. Route-based
            # tunnels carry no selectors → no proxy-id (PA's auto default).
            sels = v.get("traffic_selectors") or []
            if sels:
                pid = ET.SubElement(ak, "proxy-id")
                for i, s in enumerate(sels):
                    # proxy-id names cap at 31 chars (not the generic 63) -
                    # keep the unique -psN suffix and truncate the base, so
                    # long tunnel names (e.g. CP community-peer composites)
                    # don't fail the whole VPN section at set-time.
                    _suffix = f"-ps{i + 1}"
                    _sel_name = (s.get("name") or "").strip()
                    # NB: decide on the RAW selector name - _safe_pa_name("")
                    # returns the truthy fallback "obj", which silently named
                    # every proxy-id "obj" (collides at 2+ selectors).
                    _pid_name = (_safe_pa_name(_sel_name)[:31] if _sel_name
                                 else _safe_pa_name(name)[:31 - len(_suffix)] + _suffix)
                    pe = ET.SubElement(pid, "entry", name=_pid_name)
                    if s.get("local"):
                        ET.SubElement(pe, "local").text = s["local"]
                    if s.get("remote"):
                        ET.SubElement(pe, "remote").text = s["remote"]
                    proto = str(s.get("protocol") or "").strip()
                    if proto.isdigit():
                        ET.SubElement(
                            ET.SubElement(pe, "protocol"), "number").text = proto
            if v.get("tunnel_interface"):
                _ti = (tunnel_iface_map or {}).get(v["tunnel_interface"],
                                                   v["tunnel_interface"])
                # PAN-OS tunnel ifaces are ALWAYS tunnel.N units. A ref that
                # neither maps nor matches the shape is DANGLING (e.g. a
                # hand-edited 'tunnel2') - pushing it verbatim fails the
                # whole VPN section with "not a valid reference". Drop the
                # binding with a warn instead; the tunnel still renders.
                import re as _re
                if not _re.match(r"^tunnel\.\d+$", _ti):
                    dropped.append(DroppedField(
                        rule_id=v.get("name") or "?", field="tunnel_interface",
                        reason=f"'{_ti}' is not an existing tunnel.N interface "
                               "- fix the tunnel's interface binding",
                    ))
                else:
                    ET.SubElement(entry, "tunnel-interface").text = _ti
            if v.get("disabled"):
                ET.SubElement(entry, "disabled").text = "yes"
        _indent(root)
        return _to_xml_str(root)

    # ── Push ─────────────────────────────────────────────────────

    # Each entry: (label, delete_xpath, push_xpath, config_section_key, strand)
    # Strand assigns the step to either the Policy or the Network push.
    # Zones moved to 'network' per Migration-Note #1 - Network-Strang owns
    # zone definition + interface binding + zone-object push.
    _PUSH_STEPS = [
        ("Security Rules",  f"{_VSYS}/rulebase/security/rules", f"{_VSYS}/rulebase/security", "Security Rules",  "policy"),
        ("NAT Rules",       f"{_VSYS}/rulebase/nat/rules",      f"{_VSYS}/rulebase/nat",      "NAT Rules",       "policy"),
        # PBF + Decryption are <rulebase>s that REFERENCE address/service objects (source/dest/
        # service), so they must push AFTER objects+groups exist. Push-phase is bottom-up over this
        # list → keeping them HIGH (with Security/NAT) pushes them LATE (post-objects) and deletes
        # them EARLY (pre-objects). Their agnostic rule is edited in other tabs, but the push rides
        # the policy strand. (Phase 3/5). Prior position (bottom, near network) pushed them BEFORE
        # objects → a wipe+set / fresh-scope push failed on 'object is not an allowed keyword'.
        ("PBF Rules",       f"{_VSYS}/rulebase/pbf/rules",      f"{_VSYS}/rulebase/pbf",       "PBF Rules",      "policy"),
        ("Decryption Rules", f"{_VSYS}/rulebase/decryption/rules", f"{_VSYS}/rulebase/decryption", "Decryption Rules", "policy"),
        ("Address Groups",  f"{_VSYS}/address-group",           f"{_VSYS}",                    "Address Groups", "policy"),
        ("Service Groups",  f"{_VSYS}/service-group",           f"{_VSYS}",                    "Service Groups", "policy"),
        ("Address Objects", f"{_VSYS}/address",                 f"{_VSYS}",                    "Address Objects","policy"),
        ("Service Objects", f"{_VSYS}/service",                 f"{_VSYS}",                    "Service Objects","policy"),
        # Tags must be pushed before Security Rules (and before NAT) so
        # rule-level <tag><member>X</member></tag> + <group-tag> refs
        # resolve. Position in delete-phase (top-down) is fine wherever
        # - push-phase is bottom-up, so Tags push runs after Service
        # Objects and before Security Rules.
        ("Tags",            f"{_VSYS}/tag",                     f"{_VSYS}",                    "Tags",           "policy"),
        ("URL Categories",  f"{_VSYS}/profiles/custom-url-category", f"{_VSYS}/profiles",        "URL Categories", "policy"),
        ("Schedules",       f"{_VSYS}/schedule",                f"{_VSYS}",                    "Schedules",      "policy"),
        # (PBF + Decryption rulebases moved UP next to Security/NAT - they reference objects, so
        #  bottom-up push must run them after objects; see the note there.)
        # IPSec VPN (CE plan P3a) - Network strand. Delete top-down: tunnels
        # before gateways before the iface wipe (so a gateway never blocks its
        # local-iface delete). Push bottom-up: crypto first (gateways ref them),
        # then ifaces, then gateways, then tunnels last. Crypto uses a SENTINEL
        # no-op delete (a non-existent entry) so the vendor BUILTIN profiles
        # survive - only the rendered customs get merged in.
        ("IPSec Tunnels",   f"{_NET}/tunnel/ipsec",             f"{_NET}/tunnel",              "IPSec Tunnels",  "network"),
        ("IKE Gateways",    f"{_NET}/ike/gateway",              f"{_NET}/ike",                 "IKE Gateways",   "network"),
        ("Zones",           f"{_VSYS}/zone",                    f"{_VSYS}",                    "Zones",          "network"),
        ("Virtual Router",  f"{_NET}/virtual-router",           f"{_NET}",                     "Virtual Router", "network"),
        # Advanced Routing Engine counterpart (PAN-OS 10.2+). generate() emits
        # EITHER Virtual Router OR Logical Router per the target's routing_mode;
        # _has_data drives which one actually pushes. Same {_NET} parent → the
        # Panorama _reroot composes unchanged.
        ("Logical Router",  f"{_NET}/logical-router",           f"{_NET}",                     "Logical Router", "network"),
        ("Interfaces",      f"{_NET}/interface",                f"{_NET}/interface",           "Interfaces",     "network"),
        ("IPSec Crypto Profiles", f"{_NET}/ike/crypto-profiles/ipsec-crypto-profiles/entry[@name='__gateshift_noop__']", f"{_NET}/ike/crypto-profiles", "IPSec Crypto Profiles", "network"),
        ("IKE Crypto Profiles",   f"{_NET}/ike/crypto-profiles/ike-crypto-profiles/entry[@name='__gateshift_noop__']",   f"{_NET}/ike/crypto-profiles", "IKE Crypto Profiles",   "network"),
    ]

    # UI-label → internal section names for per-section push toggles.
    # See CheckpointDriver._SECTION_LABELS for the pattern. Policy-strand
    # only in V1 (network atomic - PA's zone+VR+interface delete cascades
    # would be unsafe to split granularly). Address/Service split into
    # Objects+Groups labels because PA users sometimes push only group
    # changes; CP groups them under one label.
    _SECTION_LABELS: dict[str, list[tuple[str, str, list[str]]]] = {
        "policy": [
            ("address_objects", "Address Objects",
                ["Address Objects", "Address Groups"]),
            ("services",        "Services",
                ["Service Objects", "Service Groups"]),
            ("tags",            "Tags",            ["Tags"]),
            ("url_categories",  "URL Categories",  ["URL Categories"]),
            ("schedules",       "Schedules",       ["Schedules"]),
            ("security_rules",  "Security Rules",  ["Security Rules"]),
            ("nat_rules",       "NAT Rules",       ["NAT Rules"]),
            ("pbf_rules",       "Policy Routing (PBF)", ["PBF Rules"]),
            ("ssl_rules",       "Decryption (SSL)", ["Decryption Rules"]),
        ],
        # V1: Network atomic.
        "network": [],
    }

    @classmethod
    def _resolve_skip_internal(cls, strand: str,
                                skip_labels: set[str] | None) -> set[str]:
        if not skip_labels:
            return set()
        out: set[str] = set()
        for key, _ui, internals in cls._SECTION_LABELS.get(strand, []):
            if key in skip_labels:
                out.update(internals)
        return out

    def _deploy_ctx(self, device: dict) -> dict:
        """Push connection for this target. CE: the device's own API (direct
        push). The enterprise Panorama driver overrides this to route via a
        Panorama (device-group + template)."""
        return {"panorama": False, "base_url": _api_url(device),
                "api_key": device.get("api_key") or ""}

    def _reroot(self, xpath: str, ctx: dict, strand: str) -> str:
        """Map a push xpath for the deploy context. CE: identity (direct push).
        The enterprise Panorama driver overrides this to re-root onto a
        device-group / template."""
        return xpath

    def push(
        self,
        *,
        device: dict,
        config: dict[str, str],
        strand: str = "policy",
        skip_sections: set[str] | None = None,
        mgmt_override: bool = False,   # ignored - PA has a dedicated OOB mgmt iface
        vpn_certs: dict | None = None,  # {vpn_hash: {cert_name, cert_pem, key_pem}}
        merge: bool = False,   # ADDITIVE-MERGE: skip the delete phase → set merges into the dest
    ) -> Iterator[StepResult]:
        # Panorama-managed target (config.panorama) routes the push THROUGH the
        # Manager (policy → device-group, network → template); a direct PA target
        # pushes to its own API. _deploy_ctx resolves the connection + xpath roots.
        ctx = self._deploy_ctx(device)
        if not ctx["panorama"]:
            # HA pair: target the ACTIVE member (PAN-OS config-sync replicates to
            # the passive; pushing to a passive would be overwritten by sync).
            # Switches to the peer if this node is passive; standalone / already-
            # active → unchanged.
            _orig_ip = device.get("mgmt_ip")
            device = self._resolve_active_node(device)
            if device.get("mgmt_ip") != _orig_ip:
                yield StepResult(
                    step="HA active-node", success=True,
                    detail=f"registered node is passive - pushing to the active "
                           f"member {device.get('mgmt_ip')}")
            ctx = self._deploy_ctx(device)  # refresh connection after any peer-switch
        base_url = ctx["base_url"]
        api_key = ctx["api_key"]
        if not api_key:
            yield StepResult(step="auth", success=False, detail="No API key configured")
            return
        if ctx["panorama"]:
            yield StepResult(
                step="Panorama target", success=True,
                detail=f"routing via Panorama {ctx['host']} → device-group "
                       f"'{ctx['dg']}' / template '{ctx['template']}'")

        skip_internal: set[str] = self._resolve_skip_internal(
            strand, skip_sections)
        steps = [
            (label, del_xp, push_xp, key)
            for label, del_xp, push_xp, key, st in self._PUSH_STEPS
            if st == strand and key not in skip_internal
        ]

        def _has_data(section_key: str) -> bool:
            xml_str = config.get(section_key, "").strip()
            if not xml_str:
                return False
            try:
                el = ET.fromstring(f"<r>{xml_str}</r>")
                return len(el.findall(".//entry")) > 0
            except Exception:
                return bool(xml_str)

        active = [(label, del_xp, push_xp, key) for label, del_xp, push_xp, key in steps if _has_data(key)]
        # REPLACE mode deletes ALL in-scope sections, not only the ones the
        # NEW generate carries data for. Skipping a delete because the new
        # section is empty leaves the target's previous push dangling: the
        # wholesale node-deletes of the other sections bypass PAN-OS'
        # reference checks, so old rules keep referencing wiped objects and
        # the next set fails ("source 'h-x' is not an allowed keyword").
        # Generalizes the earlier VPN-only special case (QA findings:
        # CP->PA VPN leftovers; logsource re-push with empty rule generate).
        if not active:
            yield StepResult(step="validate", success=False, detail="No config sections with data to push")
            return

        # HA cluster: interfaces reserved for HA (ethernet-based HA1/HA2/HA3) must
        # survive the interface wipe - deleting an HA data-interface breaks the
        # cluster on commit. Empty for a standalone device or management-based HA
        # → the wipe stays coarse (whole-subtree, fast path).
        ha_reserved: set[str] = set()
        if not ctx["panorama"] and any("interface" in dx for _, dx, _, _ in active):
            ha_reserved = self._ha_reserved_interfaces(device)

        # SSL forward-proxy needs a vsys-level forward-TRUST certificate. It is
        # a target-side prerequisite (certs are ref-only - Gateshift never
        # migrates key material), and without it the candidate config is
        # INVALID: every push step reports success and the failure only shows
        # up at commit as "forward decrypt trust cert is not configured".
        # Surface it at push time instead (QA finding, PA cluster leg).
        if (not ctx["panorama"]
                and any(k == "Decryption Rules" for _, _, _, k in active)):
            try:
                _sd = self._api_get(
                    device, self._reroot(f"{_VSYS}/ssl-decrypt", ctx, strand))
                _has_fwd = _sd.find(".//forward-trust-certificate") is not None
            except Exception:
                _has_fwd = True     # can't read → don't cry wolf
            if not _has_fwd:
                yield StepResult(
                    step="decryption prerequisite", success=True,
                    detail="the target has NO forward-trust certificate "
                           "configured (Device > Certificates > SSL "
                           "Decryption). Forward-proxy rules will push fine "
                           "but the COMMIT will fail with 'forward decrypt "
                           "trust cert is not configured' - provision the cert "
                           "before committing. Gateshift never migrates key "
                           "material.")

        # ── Delete phase (top-down order) ── skipped in ADDITIVE-MERGE mode: no wipe, so the SET
        # phase below merges the source entries into the dest's EXISTING config (PA set = union; a
        # same-name entry is overwritten, everything else already on the dest is kept).
        for label, del_xpath, _, _ in ([] if merge else steps):
            del_xpath = self._reroot(del_xpath, ctx, strand)
            step_name = f"Delete {label}"
            if "interface" in del_xpath:
                # Also wipe vsys/import/network/interface and /network/dhcp -
                # both hold per-interface references that PA validates on each
                # subsequent set. Leaving them in place causes the next push
                # step to fail with "'X' is not a valid reference".
                try:
                    _api_delete(base_url, api_key,
                                self._reroot(f"{_VSYS}/import/network/interface", ctx, strand))
                except Exception as e:
                    yield StepResult(step=f"{step_name} (vsys import)", success=False, detail=str(e))
                    return
                try:
                    _api_delete(base_url, api_key, self._reroot(f"{_NET}/dhcp", ctx, strand))
                except Exception as e:
                    yield StepResult(step=f"{step_name} (dhcp)", success=False, detail=str(e))
                    return
                for sub in ("ethernet", "tunnel", "loopback", "vlan"):
                    # HA control/data links are physical or aggregate interfaces,
                    # i.e. top-level <ethernet> (or ae) entries - never logical
                    # tunnel/loopback/vlan units. So selective-preserve applies
                    # ONLY to ethernet; the others (and the case with no reserved
                    # IFs) coarse-delete the whole subtree. (Aggregate-ethernet is
                    # not wiped at all here, so ae-based HA is preserved anyway.)
                    if sub == "ethernet" and ha_reserved:
                        try:
                            res = self._api_get(device, f"{del_xpath}/{sub}")
                            node = res.find(sub)
                            entries = (node.findall("entry") if node is not None
                                       else res.findall("entry"))
                            names = [e.get("name") for e in entries if e.get("name")]
                        except Exception:
                            names = []
                        for nm in names:
                            if nm in ha_reserved:
                                continue
                            try:
                                _api_delete(base_url, api_key,
                                            f"{del_xpath}/{sub}/entry[@name='{nm}']")
                            except Exception as e:
                                yield StepResult(step=f"{step_name} ({sub} {nm})",
                                                 success=False, detail=str(e))
                                return
                    else:
                        try:
                            _api_delete(base_url, api_key, f"{del_xpath}/{sub}")
                        except Exception as e:
                            yield StepResult(step=f"{step_name} ({sub})", success=False, detail=str(e))
                            return
                yield StepResult(
                    step=step_name, success=True,
                    detail=(f"HA-reserved preserved: {', '.join(sorted(ha_reserved))}"
                            if ha_reserved else ""))
            else:
                try:
                    _api_delete(base_url, api_key, del_xpath)
                    yield StepResult(step=step_name, success=True)
                except Exception as e:
                    yield StepResult(step=step_name, success=False, detail=str(e))
                    return

        # ── VPN identity-cert import (network strand) ──
        # Must run before IKE Gateways: a cert-auth gateway references a local
        # cert by name, and PA validates that reference at set-time. Cert + key
        # are imported as PEM; the key is protected on-device with a throwaway
        # passphrase (PA uses the key internally; IKE never re-prompts).
        if strand == "network" and vpn_certs:
            for vh, cd in vpn_certs.items():
                name = (cd or {}).get("cert_name")
                cpem = (cd or {}).get("cert_pem")
                kpem = (cd or {}).get("key_pem")
                if not (name and cpem and kpem):
                    continue
                try:
                    _api_import(base_url, api_key, "certificate", name, cpem.encode())
                    # PA caps the import passphrase at 31 chars (it only protects
                    # the key in transit/on-box; IKE uses the key internally).
                    _api_import(base_url, api_key, "private-key", name, kpem.encode(),
                                passphrase=uuid.uuid4().hex[:31])
                    yield StepResult(step=f"Import VPN cert {name}", success=True)
                except Exception as e:
                    yield StepResult(step=f"Import VPN cert {name}", success=False,
                                     detail=str(e))
                    return

        # ── Push phase (bottom-up = reversed) ──
        for label, _, push_xpath, section_key in reversed(active):
            push_xpath = self._reroot(push_xpath, ctx, strand)
            step_name = f"Push {label}"
            xml_str = config[section_key]
            if section_key == "Interfaces":
                try:
                    root = ET.fromstring(xml_str)
                    imported: list[str] = []
                    ha_skipped: list[str] = []
                    for child in root:
                        tag = child.tag
                        units = child.find("units")
                        if units is not None:
                            for entry in units:
                                if entry.get("name") in ha_reserved:
                                    # HA link (HA1/HA2/HA3) - the wipe already
                                    # preserves these; WRITING one would clobber
                                    # the cluster link on commit. Protection has
                                    # to hold on both sides (QA finding).
                                    ha_skipped.append(entry.get("name"))
                                    continue
                                _api_set(base_url, api_key,
                                         self._reroot(f"{_NET}/interface/{tag}/units", ctx, strand),
                                         _to_xml_str(entry))
                                if entry.get("name"):
                                    imported.append(entry.get("name"))
                        else:
                            for entry in child.findall("entry"):
                                if entry.get("name") in ha_reserved:
                                    ha_skipped.append(entry.get("name"))
                                    continue
                                _api_set(base_url, api_key,
                                         self._reroot(f"{_NET}/interface/{tag}", ctx, strand),
                                         _to_xml_str(entry))
                                # Aggregate MEMBER ports (they carry <aggregate-
                                # group>) are subsumed by their ae and must NOT be
                                # vsys-imported; everything else is a bindable L3
                                # iface a zone/VR can reference.
                                if entry.get("name") and entry.find("aggregate-group") is None:
                                    imported.append(entry.get("name"))
                                    # Ethernet / ae SUBINTERFACES nest under the parent's
                                    # layer3/units (not directly under the container like tunnel/
                                    # loopback/vlan units above), so the parent-only import missed
                                    # them - a zone/VR referencing ethernetX/Y.Z then dangles. Import
                                    # each subinterface alongside its parent.
                                    for sub in entry.findall("layer3/units/entry"):
                                        if sub.get("name"):
                                            imported.append(sub.get("name"))
                    # Re-establish the vsys interface import the delete phase wiped:
                    # a zone/virtual-router references interfaces by name and PA
                    # validates that ref at SET-time, so every bindable iface must
                    # be imported into the vsys before those sections push (else
                    # "'ethernetX' is not a valid reference").
                    if imported:
                        members = "".join(f"<member>{n}</member>" for n in imported)
                        _api_set(base_url, api_key,
                                 self._reroot(f"{_VSYS}/import/network/interface", ctx, strand),
                                 members)
                    _det = (f"imported {len(imported)} iface(s) into vsys"
                            if imported else "")
                    if ha_skipped:
                        _det += (("; " if _det else "")
                                 + f"HA-reserved, not written: "
                                   f"{', '.join(sorted(set(ha_skipped)))}")
                    yield StepResult(step=step_name, success=True, detail=_det)
                except Exception as e:
                    yield StepResult(step=step_name, success=False, detail=str(e))
                    return
            else:
                try:
                    _api_set(base_url, api_key, push_xpath, xml_str)
                    yield StepResult(step=step_name, success=True)
                except Exception as e:
                    yield StepResult(step=step_name, success=False, detail=str(e))
                    return

                # PA quirk: <group-tag> is silently dropped in the bulk set
                # of a Security/NAT rule (PAN-OS accepts the XML with
                # status=success but does not persist the group-tag).
                # Workaround: after the bulk push, issue a second action=set
                # per affected rule with only the <group-tag> element.
                # Verified via lab probe 2026-06-03.
                if section_key in ("Security Rules", "NAT Rules"):
                    try:
                        rules_root = ET.fromstring(f"<r>{xml_str}</r>")
                    except Exception:
                        rules_root = None
                    if rules_root is not None:
                        gt_count = 0
                        gt_failed = 0
                        for entry in rules_root.findall(".//entry"):
                            gt_el = entry.find("group-tag")
                            if gt_el is None or not (gt_el.text or "").strip():
                                continue
                            rule_name = entry.attrib.get("name", "")
                            if not rule_name:
                                continue
                            sub_xpath = f"{push_xpath}/rules/entry[@name='{rule_name}']"
                            gt_xml = f"<group-tag>{(gt_el.text or '').strip()}</group-tag>"
                            try:
                                _api_set(base_url, api_key, sub_xpath, gt_xml)
                                gt_count += 1
                            except Exception:
                                gt_failed += 1
                        if gt_count or gt_failed:
                            detail = f"{gt_count} group-tag set"
                            if gt_failed:
                                detail += f", {gt_failed} failed"
                            yield StepResult(step=f"Push {label} group-tags",
                                             success=(gt_failed == 0),
                                             detail=detail)
