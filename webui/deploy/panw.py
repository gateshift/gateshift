    def list_log_forwarding(self, *, device: dict,
                            scopes: list[str] | None = None) -> dict[str, list[dict]]:
        """Read PA's log-forwarding profile catalog.

        Returns ``{"log-forwarding": [{"name": str, "scope": str}, ...]}``.
        Profiles can live at vsys scope (``vsys1/log-settings/profiles``) or
        shared scope (``/config/shared/log-settings/profiles``); both are
        valid attachment targets on a security/NAT rule, so we merge them.

        ``scopes``: for a PANORAMA target, the device-group chain (nearest-first)
        to read instead of the firewall vsys (+ shared). None/empty = a
        standalone firewall (vsys + shared). Read-only - Gateshift doesn't manage
        log-forwarding objects.
        """
        base_url = _api_url(device)
        api_key = device.get("api_key") or ""
        if not api_key:
            raise RuntimeError("No API key configured for target")

        def _fetch(xpath: str, scope: str) -> list[dict]:
            resp = requests.post(
                f"{base_url}/api/",
                data={"type": "config", "action": "get", "xpath": xpath},
                headers={"X-PAN-KEY": api_key},
                verify=False,
                timeout=(_CONNECT_TIMEOUT, 30),
            )
            resp.raise_for_status()
            root = ET.fromstring(resp.text)
            if root.attrib.get("status") != "success":
                msg = (root.findtext("msg") or "").lower()
                if "no such node" in msg or "could not find" in msg:
                    return []
                detail = root.findtext("msg") or root.findtext(".//line") or resp.text[:300]
                raise RuntimeError(f"PAN-OS log-forwarding lookup failed: {detail}")
            # Profile entries are direct children of <profiles>; recursing
            # would also pick up <match-list>/<entry> log-type rules nested
            # inside each profile.
            return [
                {"name": e.attrib["name"], "scope": scope}
                for e in root.findall("./result/profiles/entry")
                if e.attrib.get("name")
            ]

        # Panorama: device-group chain + shared. Firewall: vsys + shared.
        # Nearer scope takes precedence in PA's lookup, so when a name exists in
        # two scopes we keep the first (nearer) entry and drop the later dup.
        if scopes:
            fetched: list[dict] = []
            for dg in scopes:
                fetched += _fetch(
                    f"{_DEV}/device-group/entry[@name='{dg}']/log-settings/profiles", dg)
            fetched += _fetch("/config/shared/log-settings/profiles", "shared")
        else:
            fetched = (_fetch(f"{_VSYS}/log-settings/profiles", "vsys")
                       + _fetch("/config/shared/log-settings/profiles", "shared"))
        # PA ships predefined log-forwarding profiles ("IoT Security Default
        # Profile", the *-enhanced-app-logging set) that ARE attachable on a rule
        # but live under /config/predefined, not the vsys/DG/shared config - merge
        # them so the catalog mirrors the GUI's log-forwarding dropdown. Appended
        # last so a custom profile of the same name (rare) wins the de-dup below.
        fetched += _fetch("/config/predefined/log-settings/profiles", "predefined")
        seen: set[str] = set()
        items: list[dict] = []
        for entry in fetched:
            if entry["name"] in seen:
                continue
            seen.add(entry["name"])
            items.append(entry)
        items.sort(key=lambda d: d["name"].lower())
        return {"log-forwarding": items}

