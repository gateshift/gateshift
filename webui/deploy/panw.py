def _pa_port_spec(port) -> str:
    """Normalize a port spec to PAN-OS form.

    CheckPoint expresses ports as COMPARISONS ('>1023', '<514', '>=1024'),
    which PA rejects - it wants a port, a range or a comma list. Translate
    those to explicit ranges (QA finding, CP→PA); 'any' becomes the full
    range, everything else passes through.
    """
    txt = str(port or "").strip()
    if not txt:
        return ""
    if txt.lower() == "any":
        return "0-65535"
    m = re.fullmatch(r"(>=|<=|>|<)\s*(\d+)", txt)
    if m:
        op, num = m.group(1), int(m.group(2))
        if op == ">":
            return f"{min(num + 1, 65535)}-65535"
        if op == ">=":
            return f"{min(num, 65535)}-65535"
        if op == "<":
            return f"1-{max(num - 1, 1)}"
        return f"1-{max(num, 1)}"
    # ASA 'neq N' arrives as '!N' - PAN-OS has no negation, but the port
    # field takes a comma list, so "everything but N" is two ranges
    # (QA finding, ASA-PA blocker).
    m = re.fullmatch(r"!\s*(\d+)", txt)
    if m:
        num = int(m.group(1))
        parts = []
        if num > 1:
            parts.append(f"1-{num - 1}")
        if num < 65535:
            parts.append(f"{num + 1}-65535")
        return ",".join(parts) or "1-65535"
    return txt


def _pa_xlate_port(value, nat_rule: dict, dropped: list) -> str:
    """PAN-OS translated-port must be a SINGLE integer 1-65535.

    Cross-vendor sources hand us range/any spellings - a FortiOS VIP without
    port-forwarding yields '0-65535' ("all ports", i.e. NO port translation),
    which PA rejects as "not a valid integer" and which would be wrong to
    force into a port anyway. Emit nothing in that case (QA finding).
    """
    txt = str(value or "").strip()
    if not txt:
        return ""
    if txt.isdigit() and 1 <= int(txt) <= 65535:
        return txt
    dropped.append(DroppedField(
        rule_id=nat_rule.get("name") or "?", field="trans_dst_port",
        reason=f"translated port {txt!r} is not a single port - PAN-OS accepts "
               "only one integer here",
        fallback="no port translation emitted (address translation kept)"))
    return ""


def _panw_set_hint(msg: str) -> str:
    """Explain PAN-OS set errors whose text points at the WRONG object.

    Replacing the zone set on a target that still holds FOREIGN security
    rules makes PAN-OS re-validate those rules and complain about THEM
    ("rules -> X -> from 'trust' is not an allowed keyword"), which reads as
    a rule-render bug though the actual blocker is the leftover rulebase
    (QA finding, Forti→PA onto a box that was itself a source).
    """
    m = (msg or "").lower()
    if ("is not an allowed keyword" in m or "is not a valid reference" in m) \
            and "rulebase" in m:
        return (" - the target still has rules referencing the zones being "
                "replaced. Push the Policy strand first (it wipes the target "
                "rulebase), or clear the rulebase on the target, then re-push "
                "Network.")
    return ""


