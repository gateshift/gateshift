def _paf_r_negate(rule, ctx):
    if ctx["force_fallback"]:
        return []
    out = []
    if rule.get("negate_source"):
        out.append(_el("negate-source", "yes"))
    if rule.get("negate_destination"):
        out.append(_el("negate-destination", "yes"))
    if rule.get("negate_service"):
        ctx["dropped"].append(DroppedField(
            rule_id=ctx["rule_id"], field="negate_service",
            reason="PAN-OS security rules have no service-negate element",
            fallback="ignored"))
