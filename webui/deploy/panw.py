# ── Helpers ──────────────────────────────────────────────────────

def _truthy(v: str | bool | None) -> bool:
    if isinstance(v, bool):
        return v
    return str(v or "").strip().lower() in ("1", "true", "yes", "on")


def _el(tag: str, text: str | None = None, **attribs) -> ET.Element:
    """Create an XML element with optional text and attributes."""
    e = ET.Element(tag, **attribs)
    if text is not None:
        e.text = text
    return e


def _member_list(parent: ET.Element, values: list[str]) -> None:
    """Append <member>val</member> children to parent, de-duplicated and
    order-preserving. PA rejects any member list (group members, zone
    interfaces, VR interfaces) that names the same entry twice
    ("members 'X' is already in use"). Duplicates arise from source configs
    that list a member twice or from name normalization collapsing two source
    names onto one safe PA name - drop the repeats here at the single choke
    point that emits every member list."""
    seen: set[str] = set()
    for v in values:
        if v in seen:
            continue
        seen.add(v)
        ET.SubElement(parent, "member").text = v


# Check Point special references that have NO PA object equivalent and mean "anything of this kind":
# the "Internet" address family (anything external - direction is carried by zones) and the default
# HTTPS-inspection service group. A CP rule referencing one otherwise renders a dangling member
# PAN-OS rejects ("'Internet' is not an allowed keyword / not a valid reference"). They collapse to
# the PA 'any' keyword, warned so the operator can tighten the migrated rule.
_CP_SPECIAL_ANY_ADDR = {"internet", "all_internet", "all internet", "all-internet"}
_CP_SPECIAL_ANY_SVC = {"https default services", "https_default_services", "https default service"}


def _pa_specials_to_any(raw, dropped, rule_id: str, field: str, specials: set, label: str) -> list[str]:
    """Address/service member list for a PA rule field: translate CP special references (`specials`,
    lowercased) → 'any' (warned via DroppedField), collapsing to ['any'] if any member ends up 'any'.
    Non-special members pass through. Returns the list (possibly empty - caller ORs in ['any'])."""
    out: list[str] = []
    for m in (raw or []):
        m = str(m).strip() if m is not None else ""
        if not m:
            continue
        if m.lower() in specials:
            if dropped is not None:
                dropped.append(DroppedField(
                    rule_id=rule_id, field=field,
                    reason=f"'{m}' is a Check Point {label} with no PA equivalent",
                    fallback="any"))
            out.append("any")
        else:
            out.append(m)
    return ["any"] if "any" in out else out


def _pa_addr_members(raw, dropped, rule_id: str, field: str) -> list[str]:
    """Source/destination address list - CP special 'internet' objects → PA 'any'."""
    return _pa_specials_to_any(raw, dropped, rule_id, field, _CP_SPECIAL_ANY_ADDR, "special object")


def _rewrite_members(members: list[str], addr_lookup: dict[str, str]) -> list[str]:
    """Resolve raw IP literals to object names via addr_lookup; dedup preserving order.

    Mirrors the rewrite _gen_rules applies to rule sources/destinations.
    Object and group names not in addr_lookup pass through unchanged
    (group→group self-mapping handled by _build_addr_lookup). The seen-set
    also heals literal duplicates like [X, X] for free.
    """
    seen: set[str] = set()
    out: list[str] = []
    for m in members:
        if not m:
            continue
        resolved = addr_lookup.get(m, m)
        if resolved in seen:
            continue
        seen.add(resolved)
        out.append(resolved)
    return out


def _to_xml_str(el: ET.Element) -> str:
    """Serialize an Element to a UTF-8 XML string (no declaration)."""
    return ET.tostring(el, encoding="unicode")


def _indent(el: ET.Element, level: int = 0) -> None:
    """Add pretty-print indentation (in-place)."""
    indent = "\n" + "  " * level
    if len(el):
        if not el.text or not el.text.strip():
            el.text = indent + "  "
        for i, child in enumerate(el):
            _indent(child, level + 1)
            if not child.tail or not child.tail.strip():
                child.tail = indent + "  " if i < len(el) - 1 else indent
    if not el.tail or not el.tail.strip():
        el.tail = indent


# ── Spec-driven PA object render (Optimization O-1) ──────────────
# One ordered list of field BUILDERS per object type drives the whole-object render
# here AND (O-2) the field-level patch. Each builder (obj, ctx) -> the child
# Element(s) it contributes to the entry, in order (PA XML child-order matters). A
# builder IS the per-field escape-hatch: trivial fields use the shared helpers,
# quirky ones (dynamic element name, port "any"→range, L3-skip) are just code - so
# migration render and optimization patch share ONE source of truth.

def _pa_spec_render(root_tag, objs, name_of, builders, ctx=None, entry_skip=None):
    root = _el(root_tag)
    seen: set[str] = set()
    for obj in objs:
        if entry_skip is not None and entry_skip(obj, ctx):
            continue
        nm = name_of(obj)
        # Two distinct source objects can sanitize to the SAME PA name (e.g. the
        # degenerate IPv6 pair "::"→h-:: and "::/32"→h--- both collapse to "h---"
        # once ':' is stripped) - PAN-OS rejects a duplicate <entry name> with
        # "'…' is already in use", failing the whole push. Emit the first, skip
        # the rest so the set stays valid. Rules that referenced the dropped
        # object already resolve to the same name, so the reference still binds.
        if nm in seen:
            continue
        seen.add(nm)
        entry = ET.SubElement(root, "entry", name=nm)
        for build in builders:
            for el in build(obj, ctx):
                entry.append(el)
    _indent(root)
    return _to_xml_str(root)


def _paf_description(obj, ctx):
    """Shared optional <description> (address / address-group / service)."""
    d = (obj.get("value") or {}).get("description")
    return [_el("description", d)] if d else []


def _paf_addr_value(obj, ctx):
    """Address value: <ip-netmask>/<ip-range>/<fqdn> (dynamic element name)."""
    val = obj.get("value", {})
    t = val.get("type", "ip-netmask")
    if t in ("ip-netmask", "ip-range", "fqdn"):
        return [_el(t, val.get("value", ""))]
    return []


def _group_pruned_members(grp, ctx):
    """(kept, lost) static members: UID-stripped, name-rewritten, then pruned to
    the objects this push actually creates (ctx['pushable_addrs']). A member
    pointing at a skipped object - e.g. a wildcard FQDN PAN-OS can't create -
    is 'lost'; PAN-OS rejects the group otherwise ('static ... is not a valid
    reference'). pushable_addrs=None disables pruning (never guess)."""
    _kept, _ = _integ.strip_uid_members(grp.get("value", {}).get("members", []))
    members = _rewrite_members(_kept, ctx["addr_lookup"])
    return _integ.prune_refs(members, ctx.get("pushable_addrs"), keep=("any",))


def _paf_addr_group_skip(grp, ctx):
    """Skip a static group left with NO members after pruning unresolvable
    references - PAN-OS rejects an empty <static> group. Reported so the empty
    group isn't silently gone."""
    if grp.get("value", {}).get("type") != "static":
        return False
    kept, lost = _group_pruned_members(grp, ctx)
    if lost and not kept:
        if ctx.get("dropped") is not None:
            ctx["dropped"].append(DroppedField(
                rule_id=grp.get("name") or "?", field="members",
                reason=f"all member(s) {lost} reference object(s) this push does "
                       "not create (e.g. wildcard FQDN) - no members left; group skipped",
                fallback="group skipped"))
        return True
    return False


def _paf_addr_group_body(grp, ctx):
    """Address-group: <static><member> (names rewritten via addr_lookup, then
    pruned to pushable objects) or <dynamic><filter>."""
    val = grp.get("value", {})
    if val.get("type") == "static":
        static = _el("static")
        members, lost = _group_pruned_members(grp, ctx)
        if lost and ctx.get("dropped") is not None:
            ctx["dropped"].append(DroppedField(
                rule_id=grp.get("name") or "?", field="member",
                reason=f"member(s) {lost} reference object(s) this push does not "
                       "create (e.g. wildcard FQDN) - pruned from the group",
                fallback="member(s) removed"))
        _member_list(static, members)
        return [static]
    if val.get("type") == "dynamic":
        dynamic = _el("dynamic")
        ET.SubElement(dynamic, "filter").text = val.get("filter", "")
        return [dynamic]
    return []


def _addr_is_wildcard_fqdn(obj) -> bool:
    """True for a wildcard FQDN address (e.g. FortiGate's factory
    '*.google.com' internet-service objects). PAN-OS FQDN objects reject a
    '*', so this push cannot create such an object - it is skipped, and any
    group member / rule reference to it must be pruned to match. Pure (no
    side effects) so both the skip and the reference-pruning agree."""
    val = obj.get("value", {})
    return val.get("type") == "fqdn" and "*" in (val.get("value") or "")


def _paf_addr_skip(obj, ctx):
    """Skip address objects PAN-OS can't represent, recording a drop so nothing
    is lost silently. Today: wildcard FQDNs - see _addr_is_wildcard_fqdn."""
    if _addr_is_wildcard_fqdn(obj):
        if ctx and ctx.get("dropped") is not None:
            val = obj.get("value", {})
            ctx["dropped"].append(DroppedField(
                rule_id=obj.get("name") or "?",
                field="fqdn",
                reason=f"wildcard FQDN '{val.get('value')}' - PAN-OS FQDN objects "
                       f"do not accept wildcards; object skipped"))
        return True
    return False


def _paf_service_skip(obj, ctx):
    """L3 protos (icmp/gre/esp/…) aren't PA service objects → skip the whole entry."""
    proto = (obj.get("value", {}).get("protocol") or "").lower()
    return proto not in _PA_SERVICE_PROTOS


def _paf_service_protocol(obj, ctx):
    """Service: <protocol><tcp|udp><port>/<source-port>; port 'any' → 0-65535
    (PA rejects a bare 'any')."""
    val = obj.get("value", {})
    proto = (val.get("protocol") or "").lower()
    proto_el = _el("protocol")
    p_el = ET.SubElement(proto_el, proto)
    port = val.get("port")
    if port:
        ET.SubElement(p_el, "port").text = _pa_port_spec(port)
    src_port = val.get("source_port")
    if src_port:
        ET.SubElement(p_el, "source-port").text = _pa_port_spec(src_port)
    return [proto_el]


def _paf_svc_group_members(grp, ctx):
    """Service-group: <members><member>."""
    members_el = _el("members")
    _kept, _ = _integ.strip_uid_members(grp.get("value", {}).get("members", []))
    _member_list(members_el, _kept)
    return [members_el]


# ── Security-rule field builders (Optimization O-1b) ─────────────
# Same spec pattern as the objects: an ordered list of per-field builders
# (rule, ctx) -> [Element] consumed for the whole-rule render AND (O-2) the
# field-level patch. The interdependent core (proto ↔ L3-app ↔ application ↔
# service) is computed ONCE per rule by _prepare_rule_render into ctx, so the
# application/service builders stay thin. Rule-LEVEL concerns (naming/dedup,
# fallback-clone emission, per-rule unsupported-field dropped-tracking) remain in
# _gen_rules' orchestration - they are not field-level. ctx carries the
# settings-derived values + lookups + the shared `dropped` list + force_fallback.

# Individual security-profile slots (PA XML tag ↔ agnostic column). Group vs.
# individual are mutually exclusive on a PA rule.
_PA_INDIV = (
    ("virus",             "av_profile"),
    ("url-filtering",     "webfilter_profile"),
    ("spyware",           "pa_spyware_profile"),
    ("vulnerability",     "pa_vulnerability_profile"),
    ("file-blocking",     "pa_file_blocking_profile"),
    ("wildfire-analysis", "pa_wildfire_profile"),
    ("data-filtering",    "pa_data_filtering_profile"),
)


def _prepare_rule_render(rule, ctx):
    """Compute the interdependent per-rule intermediates (proto, L3-app, the
    application member-list, the service member-list) once - mirrors the
    migration-faithful logic so the thin application/service builders just emit
    them. Stores rule_proto/l3_app/apps/svc_members into ctx."""
    ff = ctx["force_fallback"]
    default_app = ctx["default_app"]
    rule_proto = (rule.get("proto") or "").lower()
    l3_app = None if ff else _L3_PROTO_TO_PA_APP.get(rule_proto)
    ctx["rule_proto"] = rule_proto
    ctx["l3_app"] = l3_app

    if ff:
        apps = ["any"]
    else:
        app_str = (rule.get("application") or "").strip()
        apps = [a.strip() for a in app_str.split(",") if a.strip()] if app_str else [default_app]
        if not apps:
            apps = [default_app]
        if l3_app:
            if apps in (["any"], [default_app]):
                apps = [l3_app]
            elif l3_app not in apps:
                apps = apps + [l3_app]
    ctx["apps"] = apps

    svc_override = (rule.get("service_override") or "").strip()
    named_svcs = rule.get("services") or []
    dropped_l3_svcs = ctx["dropped_l3_svcs"]
    svc_lookup = ctx["svc_lookup"]
    if svc_override in ("any", "application-default"):
        svc_members = [svc_override]
    elif named_svcs:
        kept_svcs = [s for s in named_svcs if s not in dropped_l3_svcs]
        if kept_svcs:
            svc_members = kept_svcs
        elif l3_app or apps not in (["any"], [default_app]):
            svc_members = ["application-default"]
        else:
            svc_members = ["any"]
    elif l3_app:
        svc_members = ["application-default"]
    else:
        proto = rule_proto
        port_from = rule.get("port_from")
        port_to = rule.get("port_to")
        if proto and port_from:
            if port_to and port_to != port_from:
                port_str = f"{port_from}-{port_to}"
            else:
                port_str = str(port_from)
            svc_name = svc_lookup.get((proto, port_str))
            svc_members = [svc_name] if svc_name else ["any"]
        elif apps != ["any"] and apps != [default_app]:
            svc_members = ["application-default"]
        else:
            svc_members = ["any"]
    ctx["svc_members"] = svc_members


def _paf_r_from(rule, ctx):
    zones = ["any"] if ctx["force_fallback"] else (rule.get("src_zones") or ["any"])
    el = _el("from"); _member_list(el, zones); return [el]


def _paf_r_to(rule, ctx):
    zones = ["any"] if ctx["force_fallback"] else (rule.get("dst_zones") or ["any"])
    el = _el("to"); _member_list(el, zones); return [el]


def _paf_r_addr_side(rule, ctx, field: str, key: str):
    """source/destination member list, filtered to objects this push creates.

    Invariant I1: a reference PA can't resolve makes the COMMIT fail (the
    set call itself succeeds), so a dangling name would surface hours later
    as an invalid candidate. `pushable_addrs` is None when the caller can't
    determine the emitted set - then nothing is filtered (never guess)."""
    lk = ctx["addr_lookup"]
    names = [lk.get(x, x) for x in (rule.get(key) or ["any"])]
    kept, lost = _integ.prune_refs(names, ctx.get("pushable_addrs"),
                                   keep=("any",))
    if lost and ctx.get("dropped") is not None:
        ctx["dropped"].append(DroppedField(
            rule_id=rule.get("rule_name") or rule.get("name") or "?",
            field=field,
            reason=f"reference(s) {lost} point at object(s) this push does not "
                   "create - pruned (PAN-OS would reject the candidate at commit)",
            fallback=("side became empty → matches any" if not kept
                      else "remaining refs kept")))
    el = _el(field); _member_list(el, kept or ["any"]); return [el]


